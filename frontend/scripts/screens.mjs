const wid = page.url().split("/").pop();
await page.goto(`${WEB}/memory/${wid}`);
await page.waitForTimeout(1200);
await shot("17-memory-page");
await page.goto(WEB + "/settings");
await page.waitForTimeout(1000);
await shot("18-settings");
await page.goto(WEB + "/saves");
await page.waitForTimeout(1000);
await shot("19-saves");

await page.goto(WEB + "/education");
await page.getByRole("button", { name: /示例：《桃花源记》/ }).click();
await shot("20-education");
await page.getByTestId("edu-generate-btn").click();
await page.getByTestId("world-preview").waitFor({ timeout: 120_000 });
await shot("21-edu-preview");
await page.getByTestId("confirm-world-btn").click();
await page.getByTestId("free-input").waitFor();
