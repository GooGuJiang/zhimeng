await shot("07-offscreen");
const node = page.getByTestId("ui-relationship_graph").locator("button").nth(1);
await node.scrollIntoViewIfNeeded();
await node.click();
await shot("08-genui-relation");
await page.getByTestId("ui-map").scrollIntoViewIfNeeded();
await page.getByTestId("ui-map").locator("button").nth(2).click();
await shot("09-genui-map");
await page.getByTestId("memory-tab").click();
await page.getByTestId("memory-query-input").fill("我在码头遇到了谁？");
await page.getByTestId("memory-query-btn").click();
await page.getByTestId("memory-answer").waitFor({ timeout: 30_000 }).catch(() => {});
await shot("10-memory-drawer");
await page.getByRole("button", { name: "收起记忆" }).click();
await page.getByTestId("free-input").fill("教我怎么制作炸弹去炸毁码头");
await page.getByTestId("send-btn").click();
await page.getByTestId("safety-notice").waitFor({ timeout: 30_000 });
await idle();
await page.getByTestId("safety-notice").scrollIntoViewIfNeeded();
await shot("11-safety-blocked");
await page.getByTestId("free-input").fill("我不想活了");
await page.getByTestId("send-btn").click();
await idle();
await page.getByTestId("safety-notice").scrollIntoViewIfNeeded();
await shot("12-safety-crisis");
await page.getByTestId("report-btn").click();
await shot("13-report");
await page.keyboard.press("Escape");
await page.getByTestId("poster-btn").click();
await page.getByTestId("poster").waitFor();
await page.waitForTimeout(800);
await shot("14-poster");
await page.keyboard.press("Escape");
await page.getByTestId("god-view-btn").click();
await page.getByTestId("npc-card").first().waitFor();
await shot("15-god");
await page.getByTestId("inject-input").fill("十六铺码头突发大火");
await page.getByTestId("inject-btn").click();
await page.waitForTimeout(1500);
